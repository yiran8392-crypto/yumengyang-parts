def build():
    d = {}
    for en, (zh, ar, ru) in list(BRANDS.items()) + list(MODELS.items()):
        key = en.lower()
        for w in (zh, ar, ru):
            if w and w != en:
                d[w] = key
    for en, (zh, ar, ru) in PARTS.items():
        for w in (zh, ar, ru):
            if w:
                d.setdefault(w, en)
    for w, en in PART_WORDS.items():
        d.setdefault(w, en)
    return d


def main():
    d = build()
    js = ("/* 四语搜索词典：中文/阿拉伯语/俄语 → 英文检索词（由 models_i18n.py 生成，别手改） */\n"
          "window.SEARCH_I18N=%s;\n" % json.dumps(d, ensure_ascii=False, separators=(",", ":")))
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with io.open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(js)
    print("生成 %s：%d 条映射，%.1f KB" % (os.path.basename(OUT), len(d), len(js) / 1024.0))


